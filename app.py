import streamlit as st
import pandas as pd
import joblib

# =========================
# LOAD MODEL
# =========================
model = joblib.load("model_hypertension.pkl")

st.set_page_config(
    page_title="Hypertension Prediction",
    page_icon="❤️",
    layout="wide"
)

# =========================
# HEADER
# =========================
st.title("❤️ Hypertension Risk Prediction")
st.markdown(
    "Aplikasi Machine Learning untuk memprediksi risiko hipertensi menggunakan model XGBoost."
)

# =========================
# INPUT FORM
# =========================

col1, col2 = st.columns(2)

with col1:
    age = st.number_input(
        "Age",
        min_value=18,
        max_value=100,
        value=30
    )

    salt_intake = st.number_input(
        "Salt Intake",
        min_value=0.0,
        max_value=20.0,
        value=5.0
    )

    stress_score = st.number_input(
        "Stress Score",
        min_value=0.0,
        max_value=10.0,
        value=5.0
    )

    sleep_duration = st.number_input(
        "Sleep Duration",
        min_value=0.0,
        max_value=12.0,
        value=7.0
    )

with col2:

    bmi = st.number_input(
        "BMI",
        min_value=10.0,
        max_value=60.0,
        value=25.0
    )

    family_history = st.selectbox(
        "Family History",
        ["No", "Yes"]
    )

    smoking_status = st.selectbox(
        "Smoking Status",
        ["Non-Smoker", "Smoker"]
    )

    bp_history = st.selectbox(
        "Blood Pressure History",
        [
            "Hypertension",
            "Normal",
            "Prehypertension"
        ]
    )

    exercise_level = st.selectbox(
        "Exercise Level",
        [
            "High",
            "Low",
            "Moderate"
        ]
    )

# =========================
# PREDICT BUTTON
# =========================

if st.button("Predict Risk"):

    family_history = 1 if family_history == "Yes" else 0
    smoking_status = 1 if smoking_status == "Smoker" else 0

    # Dummy BP History
    bp_normal = 1 if bp_history == "Normal" else 0
    bp_prehyper = 1 if bp_history == "Prehypertension" else 0

    # Dummy Exercise
    ex_low = 1 if exercise_level == "Low" else 0
    ex_moderate = 1 if exercise_level == "Moderate" else 0

    input_data = pd.DataFrame({
        "Age": [age],
        "Salt_Intake": [salt_intake],
        "Stress_Score": [stress_score],
        "Sleep_Duration": [sleep_duration],
        "BMI": [bmi],
        "Family_History": [family_history],
        "Smoking_Status": [smoking_status],
        "BP_History_Normal": [bp_normal],
        "BP_History_Prehypertension": [bp_prehyper],
        "Exercise_Level_Low": [ex_low],
        "Exercise_Level_Moderate": [ex_moderate]
    })

    prediction = model.predict(input_data)[0]

    try:
        probability = model.predict_proba(input_data)[0][1]
    except:
        probability = None

    st.subheader("Prediction Result")

    if prediction == 1:
        st.error("⚠️ High Risk of Hypertension")
    else:
        st.success("✅ Low Risk of Hypertension")

    if probability is not None:
        st.metric(
            "Risk Probability",
            f"{probability*100:.2f}%"
        )

    with st.expander("Show Input Data"):
        st.dataframe(input_data)